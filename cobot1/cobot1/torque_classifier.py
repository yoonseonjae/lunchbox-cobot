# ── J2 가중치 경계값 (실측 평균 기반) ─────────────────────────────────────────
# 집게 J2 mean=-3.382, 집게+돈까스 J2 mean=-3.057 → 경계 -3.220
_J2_BOUNDARY = -3.4  # 직접 설정 (집게 ↔ 집게+돈까스 경계)

# J2 분리도: 집게+돈까스 mean > 집게 mean (덜 음수)
# → x[1] > _J2_BOUNDARY 이면 집게+돈까스
_TONGS_J2_MEAN    = _TONGS[:, 1].mean()      # ≈ -3.382
_TONGS_DONK_J2_MEAN = _TONGS_DONK[:, 1].mean()  # ≈ -3.057

# 빈그리퍼 J2 경계: 빈그리퍼(-3.94) vs 집게류(-3.22) 중간 = -3.58
_EMPTY_BOUNDARY = (_EMPTY[:, 1].mean() + _TONGS[:, 1].mean()) / 2  # ≈ -3.66

# ── 가중치 적용 LDA (J2×10, J3×3, 나머지×1) ──────────────────────────────────
_W = np.array([1.0, 10.0, 3.0, 1.0, 1.0, 1.0])

def _fit_lda_weighted(X_pos: np.ndarray, X_neg: np.ndarray):
    Xp = X_pos * _W
    Xn = X_neg * _W
    mu_pos, mu_neg = Xp.mean(0), Xn.mean(0)
    SW = (Xp - mu_pos).T @ (Xp - mu_pos) + (Xn - mu_neg).T @ (Xn - mu_neg)
    SW += np.eye(SW.shape[0]) * 1e-6
    w = np.linalg.solve(SW, mu_pos - mu_neg)
    threshold = float((Xp @ w).mean()) / 2 + float((Xn @ w).mean()) / 2
    return w, threshold

_LDA_EMPTY_vs_TONGS = _fit_lda_weighted(
    _EMPTY,
    np.vstack([_TONGS, _TONGS_DONK])
)
_LDA_TONGS_vs_DONK = _fit_lda_weighted(_TONGS_DONK, _TONGS)


def _nearest_centroid_plate(x: np.ndarray) -> str:
    best, best_d = None, float('inf')
    for cls, samples in _DATA_PLATE.items():
        d = np.linalg.norm(x - samples.mean(0))
        if d < best_d:
            best_d, best = d, cls
    return best


# ── 공개 분류기 ──────────────────────────────────────────────────────────────

class TorqueClassifier:
    """
    6축 관절 토크 벡터 → 페이로드 클래스 문자열 반환.

    predict_class(x)                  : 단일 샘플 분류
    predict_class_from_mean(samples)  : 복수 샘플 평균으로 분류 (권장)

    판별 기준 (J2 우선):
      J2 < -3.66  → 빈그리퍼
      -3.66 ≤ J2 < -3.22 → 집게
      J2 ≥ -3.22  → 집게+돈까스
      (LDA 가중치로 최종 보정)
    """

    MAIN_DISH_CLASSES = {"집게", "집게+돈까스"}
    DELIVERY_CLASSES  = {"빈그리퍼", "책받침", "책받침+가득식판"}

    def predict_class(self, torque_array) -> str:
        x = np.array(torque_array, dtype=np.float64).flatten()

        # 식판 배달 자세 판별 (J6 ≈ 0.46~0.47, J1 ≈ -0.65~-0.68 → J2 > -1.5)
        if x[1] > -1.5:
            return _nearest_centroid_plate(x)

        # 집게류 자세 (J2 < 0): J2 기반 1차 판별 후 LDA 보정
        xw = x * _W

        # Step A: 빈그리퍼 vs 집게류 (J2 경계 -3.66 + LDA)
        wa, ta = _LDA_EMPTY_vs_TONGS
        score_a = float(xw @ wa)
        if score_a >= ta:
            return "빈그리퍼"

        # Step B: 집게 vs 집게+돈까스 — J2 직접 비교 (우선)
        # x[1] > _J2_BOUNDARY(덜 음수) → 집게+돈까스, 그 이하 → 집게
        return "집게+돈까스" if x[1] > _J2_BOUNDARY else "집게"

    def predict_class_from_mean(self, samples) -> str:
        arr = np.array(samples, dtype=np.float64)
        return self.predict_class(arr.mean(axis=0))


# ── 싱글톤 ───────────────────────────────────────────────────────────────────
_classifier: TorqueClassifier | None = None


def get_classifier() -> TorqueClassifier:
    global _classifier
    if _classifier is None:
        _classifier = TorqueClassifier()
    return _classifier
